const assert=require('node:assert/strict');
const model=require('../web/source-model.js');
const catalog=[{id:'poe2',name:'Path of Exile 2',owner:'陈超'},{id:'ea-sports-fc',name:'FC 27',owner:'吴律'}];
const base={schema_version:1,status:'succeeded',version:'game-intel-'+'a'.repeat(20),collected_at:'2026-11-05T00:00:00Z',stale_after:'2026-11-05T04:00:00Z',events:[],source_status:[],coverage:{}};
const row={game_key:'poe2',event_id:'one',kind:'update',title:'更新情报',summary:'原文说明',event_date:'2026-11-06',event_time:'12:30',timezone:'UTC-08:00',source_url:'https://www.pathofexile.com/news',source_id:'official-poe',collected_at:base.collected_at,published_at:'2026-11-04',evidence:'An official source excerpt proves the event.'};
const data=model.merge(catalog,{intelligence:{...base,events:[row]}},[]);
assert.equal(data.observations[0].payload.events[0].startDate,'2026-11-06T12:30:00-08:00');
assert.equal(data.observations[0].payload.events[0].datePrecision,'instant');
assert.equal(data.observations[0].expiresAt,'2026-11-05T04:00:00Z');
const undated=model.merge(catalog,{intelligence:{...base,events:[{...row,event_date:null,event_time:null,timezone:null}]}},[]);
assert.equal(undated.observations[0].payload.events[0].startDate,null);
assert.equal(undated.observations[0].payload.events[0].datePrecision,'unknown');
assert.notEqual(undated.observations[0].payload.events[0].startDate,row.published_at);
assert.throws(()=>model.merge(catalog,{intelligence:{...base,events:[{...row,source_url:'javascript:alert(1)'}]}},[]),/invalid_event/);
assert.throws(()=>model.merge(catalog,{intelligence:{...base,events:[{...row,event_date:'2026-02-31'}]}},[]),/invalid_event/);
const community=model.merge(catalog,{},[],[{id:'community-one',gameId:'ea-sports-fc',title:'社区追踪',sourceUrl:'https://example.com/calendar',startDate:'2026-11-27',datePrecision:'day',verification:'社区追踪'}]);
assert.equal(community.observations[0].payload.events[0].verification,'社区追踪');
assert.equal(community.observations[0].observedAt,null);
const partial=model.merge(catalog,{intelligence:{...base,events:[row]}},['intelligence']);
assert.equal(partial.observations.length,2);
assert.equal(partial.failures[0],'intelligence');
const prices=model.merge(catalog,{intelligence:{...base,events:[row]}},[]);
assert.deepEqual(prices.records,[]);
const context={window:{}};require('node:vm').runInNewContext(require('node:fs').readFileSync(require('node:path').join(__dirname,'../web/catalog.js'),'utf8'),context);
const seeded=model.merge(context.window.FS_MONITOR_CATALOG,{},[],context.window.FS_MONITOR_CALENDAR);
assert.equal(seeded.observations.filter(o=>o.kind==='calendar').length,18);
assert.ok(seeded.observations.every(o=>o.payload.events[0].sourceLabel));
const failedAttempt=model.merge(catalog,{intelligence:{...base,events:[row]},intelligence_status:{schema_version:1,status:'failed',attempted_at:'2026-11-05T01:00:00Z',reason:'model_http_429'}},[]);
assert.ok(failedAttempt.failures.includes('intelligence采集失败'));
assert.equal(failedAttempt.observations.length,2);
const carried=model.merge(catalog,{intelligence:{...base,events:[{...row,carried_forward:true,collected_at:'2026-11-04T00:00:00Z'}]}},[]);
assert.equal(carried.observations[0].expiresAt,'2026-11-04T04:00:00.000Z');
const ignored=model.merge(catalog,{daily:base},[]);
assert.equal(ignored.observations.length,0);
const seoFailure=model.merge(catalog,{seo_status:{schema_version:1,status:'unavailable',collected_at:base.collected_at}},[]);
assert.ok(seoFailure.failures.includes('MMOEXP资讯采集失败'));
console.log('source-model: passed, including all 18 original FC calendar records');
