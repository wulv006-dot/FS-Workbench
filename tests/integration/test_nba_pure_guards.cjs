const assert = require('node:assert/strict');
const p = require('../../opt/nba-reprice/backend/api_security.js');
const base={mode:'token', token:'',operators:{},operatorName:'shared'};
const req=(method='POST',extra={})=>({method,headers:{'content-type':'application/json',...extra},socket:{remoteAddress:'127.0.0.1'}});
assert.equal(p.resolveIdentity(req(),base),null);
const config={...base,operators:{syntheticAdmin:'wulv',syntheticReader:'reader',syntheticDY:'DY',syntheticOther:'fstech'}};
assert.deepEqual(p.resolveIdentity(req('POST',{'x-access-token':'syntheticAdmin'}),config),{user:'wulv',admin:true});
assert.equal(p.resolveIdentity(req('POST',{'x-access-token':'syntheticReader'}),config).admin,false);
assert.equal(p.resolveIdentity(req('POST',{'x-access-token':'syntheticOther'}),config).admin,false);
assert.equal(p.resolveIdentity(req('POST',{'x-access-token':'syntheticDY'}),config).admin,true);
const proxy={...base,mode:'proxy'};
assert.equal(p.resolveIdentity({headers:{'x-auth-user':'wulv','x-auth-role':'admin'},socket:{remoteAddress:'192.0.2.1'}},proxy),null);
assert.equal(p.resolveIdentity(req('POST',{'x-auth-user':'dy','x-auth-role':'admin'}),proxy).admin,false);
for (const method of ['GET','HEAD','PUT','DELETE']) assert.equal(p.checkApply(req(method),{user:'wulv',admin:true},true,[]).status,405);
assert.equal(p.checkApply(req(),null,true,[]).status,401);
assert.equal(p.checkApply(req(),{user:'reader',admin:false},true,[]).status,403);
assert.equal(p.checkApply(req(),{user:'wulv',admin:true},false,[]).status,403);
assert.equal(p.checkApply(req('POST',{'content-type':'text/plain'}),{user:'wulv',admin:true},true,[]).status,415);
assert.equal(p.checkApply(req('POST',{origin:'https://evil.invalid'}),{user:'wulv',admin:true},true,['https://platform.invalid']).status,403);
assert.equal(p.checkApply(req(),{user:'wulv',admin:true},true,[]),null);
for (const price of [0,-1,Infinity,NaN,'0.01',Number.MAX_VALUE]) assert.throws(()=>p.validateApply({confirm:'NBA_PRICE_APPLY',platforms:[{area:'PS',price}]}));
assert.throws(()=>p.validateApply({platforms:[{area:'PS',price:0.01}]}));
assert.throws(()=>p.validateApply({confirm:'NBA_PRICE_APPLY',platforms:[{area:'PS',price:0.01},{area:'PS',price:0.02}]}));
p.validateApply({confirm:'NBA_PRICE_APPLY',platforms:[{area:'PS',price:0.01},{area:'Xbox',price:0.02},{area:'PC',price:0.03}]});
console.log(JSON.stringify({passed:true,scope:'pure NBA identity/method/write/confirmation/price guards; no server/app/network/process',assertions:28}));
